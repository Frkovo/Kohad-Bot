import { readFileSync } from "node:fs"
import { fileURLToPath } from "node:url"
import { computeB50, type B50Entry, type B50Input, type B50Result, type ChartInfo } from "../b50/compute.js"
import { UserError, type RemoteServer, type ScoreRecord, type Snapshot } from "./registry.js"
import { t } from "../messages.js"

export const VERSIONS: string[] = JSON.parse(readFileSync(new URL("../../assets/data/versions.json", import.meta.url), "utf8"))
type Sheet = { internalId?: number; type: string; difficulty: string; internalLevelValue: number; multiverInternalLevelValue?: Record<string, number>; level: string; version: string; regions: Record<string, boolean>; noteCounts?: { total?: number } }
export type DxData = { updateTime: string; songs: { songId: string; title: string; imageName?: string; sheets: Sheet[] }[] }
let data: DxData | undefined
export function dxData(): DxData { return data ??= JSON.parse(readFileSync(process.env.B50_DXDATA_FILE || fileURLToPath(new URL("../../assets/data/dxdata.json", import.meta.url)), "utf8")) }
const difficulties = ["basic", "advanced", "expert", "master", "remaster"]
const titleKey = (title: string, type: string, level: number) => JSON.stringify([title.trim(), type, level])
// Latest version each region has released. Charts from later versions (e.g. intl MAGiCAL, announced but not out) are excluded.
// B15 = this version and the one before it (DXRating rule). Update here when a region releases a new version.
// Generated by scripts/update-catalog.mjs from the chart data; fallback keeps the bot working if the file is missing.
export const REGION_CURRENT_VERSION: Record<"jp" | "intl", string> = readRegionVersions()
function readRegionVersions(): Record<"jp" | "intl", string> {
  const fallback = { jp: "MAGiCAL", intl: "CiRCLE PLUS" }
  try { const raw = JSON.parse(readFileSync(new URL("../../assets/data/region-versions.json", import.meta.url), "utf8")); return { jp: raw.jp ?? fallback.jp, intl: raw.intl ?? fallback.intl } }
  catch { return fallback }
}
export function regionCatalog(region: "jp" | "intl", requested?: string, catalog = dxData()) {
  const version = requested || REGION_CURRENT_VERSION[region]
  const current = VERSIONS.indexOf(version)
  if (current < 0) throw new UserError(t("catalog.versionInvalid"))
  const index = new Map<string, ChartInfo>(), titles = new Map<string, string | null>()
  for (const [songIndex, song] of catalog.songs.entries()) for (const sheet of song.sheets) {
    const release = VERSIONS.indexOf(sheet.version), level = difficulties.indexOf(sheet.difficulty)
    if (!sheet.regions[region] || release < 0 || release > current || level < 0 || !["std", "dx"].includes(sheet.type)) continue
    const type = sheet.type === "dx" ? "DX" : "SD", key = titleKey(song.songId, type, level)
    const ds = Number(sheet.multiverInternalLevelValue?.[version] ?? sheet.internalLevelValue)
    if (!(ds > 0)) continue
    index.set(key, { musicId: sheet.internalId !== undefined ? sheet.internalId % 10000 : songIndex + 1, title: song.title, type, level,
      ds, levelLabel: sheet.level, version: release, displayId: sheet.internalId === undefined ? undefined : String(sheet.internalId), jacketHash: song.imageName, maxDxScore: sheet.noteCounts?.total ? sheet.noteCounts.total * 3 : undefined,
      isNew: current >= 25 ? release >= current - 1 : release === current })
    for (const title of new Set([song.title, song.songId])) {
      const lookup = titleKey(title, type, level)
      titles.set(lookup, titles.has(lookup) && titles.get(lookup) !== key ? null : key)
    }
  }
  return { version, index, titles, revision: catalog.updateTime }
}
export function calculateRemote(server: RemoteServer, snapshot: Snapshot, mode: "b50" | "fitb50" | "pc50") {
  if (mode === "fitb50") throw new UserError(t("b50.fitUnsupported"))
  if (mode === "pc50" && !snapshot.countsComplete) throw new UserError(t("catalog.countsIncomplete"))
  if (server === "jp" || server === "intl") {
    const catalog = regionCatalog(server, process.env[server === "jp" ? "NET_JP_VERSION" : "NET_INTL_VERSION"])
    let unresolved = 0
    const inputs: B50Input[] = snapshot.records.flatMap(record => {
      const key = catalog.titles.get(titleKey(record.title, record.type, record.level)), chart = key ? catalog.index.get(key) : undefined
      if (!chart) { unresolved++; return [] }
      return [{ ...record, musicId: chart.musicId, chartKey: key! }]
    })
    const result = computeB50(inputs, catalog.index, { newVersionFrom: VERSIONS.indexOf(catalog.version), mode, useChartBuckets: true, ratingPolicy: "net" })
    result.missing += unresolved
    return { result, version: catalog.version, note: t("catalog.noteRating", { revision: catalog.revision.slice(0, 10) }) }
  }
  const index = new Map<string, ChartInfo>(), inputs: B50Input[] = [], unknown: B50Entry[] = []
  for (const [i, record] of snapshot.records.entries()) {
    const key = titleKey(record.musicId === undefined ? record.title : String(record.musicId), record.type, record.level)
    if (!(Number(record.ds) > 0) || typeof record.isNew !== "boolean" || !Number.isFinite(record.version)) {
      // A play whose chart the bundled data does not know is kept as 未知歌曲 so the card still shows the score.
      if (record.ds === undefined && record.musicId !== undefined && mode !== "pc50") unknown.push(unknownEntry(record))
      continue
    }
    index.set(key, { musicId: record.musicId ?? i + 1, type: record.type, level: record.level, title: record.title,
      displayId: record.musicId === undefined ? undefined : String(record.musicId), ds: record.ds!, version: record.version!, levelLabel: String(record.ds), isNew: record.isNew, maxDxScore: record.maxDxScore })
    inputs.push({ ...record, musicId: record.musicId ?? i + 1, chartKey: key })
  }
  if (!index.size && snapshot.records.length) throw new UserError(t("catalog.privateMissingInfo"))
  // MuNET runs the international-style chart data, so it uses the DXRating-compatible NET policy without a switch.
  const policy = server === "mumur" ? "net" : process.env[`${server.toUpperCase()}_RATING_POLICY`]
  if (policy !== "cn" && policy !== "net") throw new UserError(t("catalog.ratingPolicy"))
  const result = computeB50(inputs, index, { newVersionFrom: 0, mode, useChartBuckets: true, ratingPolicy: policy })
  result.missing += snapshot.records.length - inputs.length
  fillUnknown(result, unknown)
  return { result, version: snapshot.version ?? t("catalog.privateVersion"), note: mode === "pc50" ? t("catalog.privateCounts") : t("catalog.privateLocal") }
}
function unknownEntry(record: ScoreRecord): B50Entry {
  return { musicId: record.musicId!, level: record.level, type: record.type, title: t("mumur.unknownSong"), ds: 0, levelLabel: "?",
    achievement: record.achievement, dxScore: record.dxScore, fc: record.fc, fs: record.fs, ra: 0, version: 0, playCount: record.playCount,
    maxDxScore: record.maxDxScore, unknown: true }
}
// Unknown charts take only empty slots (rating 0), so they never displace a chart that has a rating. B15 is filled first.
function fillUnknown(result: B50Result, unknown: B50Entry[]) {
  const pool = [...unknown]
  result.b15 = [...result.b15, ...pool.splice(0, Math.max(0, 15 - result.b15.length))]
  result.b35 = [...result.b35, ...pool.splice(0, Math.max(0, 35 - result.b35.length))]
}
